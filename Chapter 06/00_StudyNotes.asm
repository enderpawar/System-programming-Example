; ╔══════════════════════════════════════════════════════════╗
; ║       SECTION 1: 불리언 & 비교 명령어                    ║
; ╚══════════════════════════════════════════════════════════╝
;
; ─────────────────────────────────────────────────────────
; 1-1. 명령어별 동작 & 플래그 영향 (시험 단골!)
; ─────────────────────────────────────────────────────────
;   ┌────────┬──────────────────────┬─────────────────────┐
;   │ 명령어 │ 동작                 │ 플래그              │
;   ├────────┼──────────────────────┼─────────────────────┤
;   │ AND    │ 비트곱(비트 끄기)    │ OF=0,CF=0 / SF,ZF,PF│
;   │ OR     │ 비트합(비트 켜기)    │ OF=0,CF=0 / SF,ZF,PF│
;   │ XOR    │ 배타합(토글/패리티)  │ OF=0,CF=0 / SF,ZF,PF│
;   │ NOT    │ 1의 보수(전체 반전)  │ 영향 없음! ★        │
;   │ TEST   │ AND하되 결과 버림    │ OF=0,CF=0 / SF,ZF,PF│
;   │ CMP    │ 뺄셈하되 결과 버림   │ OF,SF,ZF,CF,AF,PF   │
;   └────────┴──────────────────────┴─────────────────────┘
;
;   ★ NOT 은 플래그를 전혀 바꾸지 않는다 (자주 출제!)
;   ★ AND/OR/XOR/TEST 는 항상 OF=0, CF=0
;
; ─────────────────────────────────────────────────────────
; 1-2. 비트 마스킹 활용 (암기)
; ─────────────────────────────────────────────────────────
;   · 비트 끄기(clear) → AND  (마스크의 해당 비트=0)
;   · 비트 켜기(set)   → OR   (마스크의 해당 비트=1)
;   · 비트 토글        → XOR  (마스크의 해당 비트=1)
;
;   대문자화: AND ch, 11011111b (DFh) → 비트5 클리어
;   숫자→ASCII: OR digit, 30h
;
; ─────────────────────────────────────────────────────────
; 1-3. 비트 매핑 집합
; ─────────────────────────────────────────────────────────
;   여집합 → NOT,  교집합 → AND,  합집합 → OR
;
; ─────────────────────────────────────────────────────────
; 1-4. XOR 의 가역성 (암호화)
; ─────────────────────────────────────────────────────────
;   (X XOR Y) XOR Y = X
;   같은 키로 두 번 XOR → 원래 값 → 대칭키 암호화의 원리
;
; ─────────────────────────────────────────────────────────
; 1-5. CMP 결과 정리 (부호 없는 비교)
; ─────────────────────────────────────────────────────────
;   목적지 < 소스 → CF=1
;   목적지 = 소스 → ZF=1
;   목적지 > 소스 → CF=0, ZF=0
;
;   ☑ 퀴즈 1: mov ax,5 / cmp ax,10 후 CF, ZF 는?
;     (답: CF=1, ZF=0  — 5-10 은 빌림 발생)

; ╔══════════════════════════════════════════════════════════╗
; ║       SECTION 2: 조건부 점프 (Jcond) 4분류              ║
; ╚══════════════════════════════════════════════════════════╝
;
; ─────────────────────────────────────────────────────────
; 2-1. (1) 특정 플래그 값
; ─────────────────────────────────────────────────────────
;   JZ/JNZ(ZF) JC/JNC(CF) JO/JNO(OF) JS/JNS(SF) JP/JNP(PF)
;
; 2-2. (2) 같음 / (E)CX
;   JE(=)=JZ,  JNE(≠)=JNZ,  JCXZ(CX=0),  JECXZ(ECX=0)
;
; 2-3. (3) 부호 없는(unsigned) 비교  ★ A/B
;   JA/JNBE(>)  JAE/JNB(>=)  JB/JNAE(<)  JBE/JNA(<=)
;
; 2-4. (4) 부호 있는(signed) 비교    ★ G/L
;   JG/JNLE(>)  JGE/JNL(>=)  JL/JNGE(<)  JLE/JNG(<=)
;
;   ★★★ 시험 최빈출 ★★★
;     부호 없는 → A(Above)/B(Below)
;     부호 있는 → G(Greater)/L(Less)
;     (이 구분을 틀리면 음수 비교에서 논리 버그!)
;
;   ☑ 퀴즈 2: 부호 있는 정수 EAX > EBX 일 때 점프하는 명령은?
;     (답: JG  (또는 JNLE))
;   ☑ 퀴즈 3: 부호 없는 정수 EAX < EBX 일 때 점프하는 명령은?
;     (답: JB  (또는 JNAE))

; ╔══════════════════════════════════════════════════════════╗
; ║       SECTION 3: 조건부 루프 명령어                      ║
; ╚══════════════════════════════════════════════════════════╝
;
;   LOOP        : ECX-- 후 ECX!=0 이면 점프
;   LOOPZ/LOOPE : ECX-- 후 (ECX!=0 그리고 ZF=1) 이면 점프
;   LOOPNZ/LOOPNE: ECX-- 후 (ECX!=0 그리고 ZF=0) 이면 점프
;
;   ★ LOOPxx 는 ZF를 만들지 않음 → 직전 명령의 ZF를 본다
;   ★ ADD 등이 ZF를 덮어쓰므로 PUSHFD/POPFD 로 플래그 보존
;
;   ☑ 퀴즈 4: LOOPE 가 점프하는 두 조건은?
;     (답: ECX != 0  그리고  ZF = 1)

; ╔══════════════════════════════════════════════════════════╗
; ║       SECTION 4: 조건 구조 변환                          ║
; ╚══════════════════════════════════════════════════════════╝
;
; ─────────────────────────────────────────────────────────
; 4-1. IF-ELSE 변환 정석
; ─────────────────────────────────────────────────────────
;   조건을 '반대로' 뒤집어 ELSE 레이블로 점프하면 코드가 간결
;   if(a==b) X=1; else X=2;
;     mov eax,a / cmp eax,b / jne L1 / mov X,1 / jmp L2
;     L1: mov X,2 / L2:
;
; 4-2. 복합 조건
;   AND : 첫 조건 거짓이면 즉시 탈출(단축 평가)
;   OR  : 첫 조건 참이면 즉시 실행부로 분기
;
; 4-3. WHILE
;   조건을 반대로 뒤집어 endwhile 로 점프
;   변수끼리 비교 불가 → 한쪽을 레지스터로 옮긴 뒤 비교
;
; 4-4. 고수준 디렉티브
;   .IF / .ELSEIF / .ELSE / .ENDIF  (.IF, .ENDIF 필수)
;   .WHILE / .ENDW  (조건 먼저 검사)
;   .REPEAT / .UNTIL (몸체 먼저 실행 후 검사)
;   ★ 레지스터끼리 .IF 비교 시 MASM은 기본적으로 '부호 없는'
;     비교(JBE 등)를 생성한다 (시험 주의)

; ╔══════════════════════════════════════════════════════════╗
; ║       SECTION 5: 흔한 실수 모음                          ║
; ╚══════════════════════════════════════════════════════════╝
;
; ✗ 실수 1: 부호 있는 값에 A/B 점프 사용
;   음수 비교에서 JA/JB는 오답 → JG/JL 사용해야 함
;
; ✗ 실수 2: NOT 후 플래그가 바뀌었다고 가정
;   NOT 은 플래그 무영향!
;
; ✗ 실수 3: LOOPNZ 앞에서 플래그 보존 안 함
;   ADD/INC 등이 ZF를 덮어씀 → PUSHFD/POPFD 필요
;
; ✗ 실수 4: 변수끼리 직접 CMP
;   cmp val1, val2  ← 메모리-메모리 불가, 한쪽을 레지스터로
;
; ✗ 실수 5: TEST/CMP 가 피연산자를 바꾼다고 착각
;   둘 다 결과를 버리고 플래그만 변경 (피연산자 불변)

; ╔══════════════════════════════════════════════════════════╗
; ║       SECTION 6: 퀴즈 정답 모음                          ║
; ╚══════════════════════════════════════════════════════════╝
;
; Q1: mov ax,5 / cmp ax,10 → CF=1, ZF=0
; Q2: 부호 있는 > → JG (JNLE)
; Q3: 부호 없는 < → JB (JNAE)
; Q4: LOOPE 점프 조건 → ECX!=0 그리고 ZF=1
