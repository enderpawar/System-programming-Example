; ============================================================
; 파일명  : 14_BooleanComparison.asm
; 설  명  : 6장 조건 처리 (1) - 불리언 & 비교 명령어
;           AND / OR / XOR / NOT / TEST / CMP
;           (PDF 06_Conditional Processing - Boolean and Comparison)
; ============================================================
;
; [핵심] 불리언 명령어는 비트 단위(bitwise) 연산을 수행하며
;        조건 분기를 위해 CPU 상태 플래그를 변경한다.
;
;   영향받는 플래그 요약 (시험 단골!)
;   ┌────────┬───────────────────────────────────────────┐
;   │ 명령어 │ 플래그 영향                                │
;   ├────────┼───────────────────────────────────────────┤
;   │ AND    │ OF=0, CF=0  / SF,ZF,PF 는 결과에 따라      │
;   │ OR     │ OF=0, CF=0  / SF,ZF,PF 는 결과에 따라      │
;   │ XOR    │ OF=0, CF=0  / SF,ZF,PF 는 결과에 따라      │
;   │ NOT    │ 어떤 플래그도 변경하지 않음! (시험 주의)   │
;   │ TEST   │ OF=0, CF=0  / SF,ZF,PF (AND와 동일, 결과   │
;   │        │ 는 버림 → 목적지 불변)                     │
;   │ CMP    │ OF,SF,ZF,CF,AF,PF (뺄셈했다고 가정한 결과) │
;   └────────┴───────────────────────────────────────────┘
; ============================================================

.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.DATA
    ; 비트 매핑 집합 예제용 (SetX, SetY)
    SetX    DWORD 80000007h     ; 원소 0,1,2,31 이 집합에 속함
    SetY    DWORD 00000101h     ; 원소 0,8 이 집합에 속함

    ; 대문자 변환 예제용 문자 배열
    array   BYTE  "abcde"       ; 소문자 5글자

    ; TEST / 상태비트 검사 예제용
    status  BYTE  00100000b     ; 외부 장치 상태 바이트 (비트5=1)

.CODE
main PROC

    ; ==========================================================
    ; 1. AND 명령어 - 비트 단위 논리곱
    ;    형식: AND 목적지, 소스
    ;    규칙: 두 피연산자 크기 동일, 즉치는 최대 32비트
    ;    용도: 특정 비트를 0으로 지우기(clear, 마스킹)
    ;          → 마스크 비트가 0인 자리는 0, 1인 자리는 원본 유지
    ; ==========================================================

    ; [예제] 장치 리셋: 비트 0과 비트 3을 0으로 지우기
    ;   마스크 = 11110110b (비트0,3 자리만 0)
    mov al, 11111111b
    and al, 11110110b       ; AL = 11110110b (비트0,3 클리어)

    ; [예제] 소문자 -> 대문자 변환
    ;   'a'(61h)와 'A'(41h)는 비트5만 다름
    ;   11011111b(=0DFh)와 AND 하면 비트5만 0으로 → 대문자화
    mov al, 'a'             ; 01100001b
    and al, 11011111b       ; AL = 01000001b = 'A'

    ; ==========================================================
    ; 2. OR 명령어 - 비트 단위 논리합
    ;    용도: 특정 비트를 1로 켜기(set)
    ;          → 마스크 비트가 1인 자리는 1, 0인 자리는 원본 유지
    ; ==========================================================

    ; [예제] 제어 바이트의 비트 2만 1로 설정 (나머지 보존)
    mov al, 11100011b
    or  al, 00000100b       ; AL = 11100111b (비트2 set)

    ; [예제] 0~9 숫자를 ASCII 문자로 변환 (OR 30h)
    mov al, 6
    or  al, 30h             ; AL = 36h = '6'

    ; ==========================================================
    ; 3. 비트 매핑 집합 (Bit-Mapped Sets)
    ;    이진수의 각 비트로 집합 원소의 소속 여부 표현
    ; ==========================================================

    ; 여집합(Complement): NOT
    mov eax, SetX
    not eax                 ; EAX = SetX의 여집합

    ; 교집합(Intersection): AND
    mov eax, SetX
    and eax, SetY           ; EAX = SetX ∩ SetY = 00000001h

    ; 합집합(Union): OR
    mov eax, SetX
    or  eax, SetY           ; EAX = SetX ∪ SetY = 80000107h

    ; ==========================================================
    ; 4. XOR 명령어 - 비트 단위 배타적 논리합
    ;    같으면 0, 다르면 1
    ;    특징: 같은 값으로 두 번 XOR 하면 원래 값으로 복원
    ;          → 간단한 대칭키 암호화에 활용
    ; ==========================================================

    ; [예제] XOR 두 번 적용 → 원상복구 (암호화/복호화 동일 키)
    mov al, 'A'             ; 평문 41h
    xor al, 0FFh            ; 암호화: AL = BEh
    xor al, 0FFh            ; 복호화: AL = 41h = 'A' (원래 값)

    ; [예제] 패리티 검사: 값을 바꾸지 않고 PF 확인
    ;   값을 0과 XOR → 값 불변, PF만 갱신
    mov al, 10110101b       ; 1비트 개수 = 5개(홀수)
    xor al, 0               ; PF = 0 (홀수 패리티), AL 불변

    ; ==========================================================
    ; 5. NOT 명령어 - 1의 보수(모든 비트 반전)
    ;    ★ 어떤 플래그에도 영향을 주지 않음 (시험 주의!)
    ; ==========================================================
    mov al, 0F0h
    not al                  ; AL = 0Fh (F0h의 1의 보수)

    ; ==========================================================
    ; 6. TEST 명령어 - AND를 수행하되 결과는 버림
    ;    목적지 피연산자는 변하지 않고 플래그만 설정
    ;    용도: 특정 비트가 켜져 있는지 검사
    ;    ★ 검사한 모든 비트가 0일 때만 ZF=1
    ; ==========================================================

    ; [예제] AL의 비트0 또는 비트3이 켜져 있는지 검사
    mov al, status
    test al, 00001001b      ; 비트0,3 검사 (AL은 변하지 않음)
    ; → 검사 비트가 모두 0이면 ZF=1, 하나라도 1이면 ZF=0

    ; ==========================================================
    ; 7. CMP 명령어 - 정수 비교 (암시적 뺄셈)
    ;    형식: CMP 목적지, 소스   (목적지 - 소스, 결과는 버림)
    ;    피연산자는 변하지 않고 플래그만 변경
    ;
    ;    [부호 없는 비교 결과]
    ;      목적지 < 소스  → CF=1
    ;      목적지 > 소스  → CF=0, ZF=0
    ;      목적지 = 소스  → ZF=1
    ; ==========================================================

    ; [예제 A] 5와 10 비교 → 5-10 은 빌림 발생 → CF=1
    mov ax, 5
    cmp ax, 10              ; CF=1 (빌림 발생)

    ; [예제 B] 1000과 1000 비교 → 결과 0 → ZF=1
    mov ax, 1000
    cmp ax, 1000            ; ZF=1

    ; [예제 C] 105와 0 비교 → 양수, 0 아님 → ZF=0, CF=0
    mov ax, 105
    cmp ax, 0               ; ZF=0, CF=0

    ; ==========================================================
    ; 8. 개별 CPU 플래그 설정/해제 기법
    ; ==========================================================
    ; ZF 설정: TEST 또는 AND 를 0과 / ZF 해제: OR 을 1과
    ; CF 설정: STC 명령 / CF 해제: CLC 명령
    stc                     ; CF = 1
    clc                     ; CF = 0

    INVOKE ExitProcess, 0
main ENDP

END main
