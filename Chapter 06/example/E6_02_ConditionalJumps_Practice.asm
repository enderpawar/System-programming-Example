; ============================================================
; [시험 대비 빈칸 채우기] 6장 - 조건부 점프 (Jcond)
; 빈칸( ______ )을 채우세요. 정답은 E6_02_ConditionalJumps_Answer.asm 참고.
; ============================================================

.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.DATA
    V1 WORD 30
    V2 WORD 10
    V3 WORD 20

.CODE
main PROC

; ──────────────────────────────────────────────────────────
; [문제 1] 조건부 점프 4분류 — 점프 명령을 채우세요.
;
;   (부호 없는 비교)         (부호 있는 비교)
;   >  : (1)______           >  : (5)______
;   >= : (2)______           >= : (6)______
;   <  : (3)______           <  : (7)______
;   <= : (4)______           <= : (8)______
;
;   ★ 부호 없는 → (9)______ / (10)______ 로 시작
;     부호 있는 → (11)______ / (12)______ 로 시작
; ──────────────────────────────────────────────────────────

; [문제 2] 동치 관계 — 빈칸을 채우세요.
;
;   JE  = (13)______      (둘 다 ZF=1 이면 점프)
;   JNE = (14)______      (둘 다 ZF=0 이면 점프)

; ──────────────────────────────────────────────────────────
; [문제 3] 두 정수 중 큰 값(부호 없는) — 빈칸을 채우세요.
;   EAX, EBX 중 큰 값을 EDX 로.
;
;   mov edx, eax          ; EAX가 크다고 가정
;   cmp eax, ebx
;   (15)______ L1         ; EAX >= EBX 이면 L1 (부호 없는)
;   mov edx, ebx
;   L1:
; ──────────────────────────────────────────────────────────

; [문제 4] 세 정수 중 최솟값(부호 없는) — 빈칸을 채우세요.
;   V1=30, V2=10, V3=20
;
;   mov ax, V1
;   cmp ax, V2
;   (16)______ L1         ; AX <= V2 이면 L1
;   mov ax, V2
;   L1:
;   cmp ax, V3
;   (17)______ L2         ; AX <= V3 이면 L2
;   mov ax, V3
;   L2:
;   ; AX = (18)______     (최솟값)

; ──────────────────────────────────────────────────────────
; [문제 5] 조건 구조 구현의 2단계 — 빈칸을 채우세요.
;
;   1) (19)______, AND, SUB 등이 CPU 상태 (20)______ 를 변경
;   2) (21)______ 점프 명령이 그 플래그를 검사하여 분기

    ; (실행용 코드)
    mov ax, V1
    cmp ax, V2
    jbe L1
    mov ax, V2
L1: cmp ax, V3
    jbe L2
    mov ax, V3
L2:
    INVOKE ExitProcess, 0
main ENDP
END main
