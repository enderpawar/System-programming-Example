; ============================================================
; [시험 대비 빈칸 채우기] 6장 - 조건 구조 & 조건부 루프
; 빈칸( ______ )을 채우세요. 정답은 E6_03_Structures_Answer.asm 참고.
; ============================================================

.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.DATA
    op1 DWORD 5
    op2 DWORD 10
    X   DWORD 0
    array    SWORD -3, -6, -1, -10, 10, 30, 40, 4

.CODE
main PROC

; ──────────────────────────────────────────────────────────
; [문제 1] IF-ELSE 변환 — 빈칸을 채우세요.
;   if (op1 == op2)  X = 1;
;   else             X = 2;
;
;   mov eax, op1
;   cmp eax, op2
;   (1)______ L1          ; 다르면 ELSE로 (조건을 반대로 뒤집음)
;   mov X, 1
;   (2)______ L2          ; then 끝나면 건너뜀
;   L1: mov X, 2
;   L2:
; ──────────────────────────────────────────────────────────

; [문제 2] 복합 조건 AND — 빈칸을 채우세요.
;   if (al > 10 && al < 20)  X = 1;
;
;   cmp al, 10
;   (3)______ next        ; al <= 10 이면 거짓 → 탈출
;   cmp al, 20
;   (4)______ next        ; al >= 20 이면 거짓 → 탈출
;   mov X, 1
;   next:
;
;   ※ 첫 조건이 거짓이면 둘째를 평가하지 않는 것을 (5)______ 평가라 함

; ──────────────────────────────────────────────────────────
; [문제 3] WHILE 변환 — 빈칸을 채우세요.
;   while (val1 < val2)  val1++;   (부호 있는 정수)
;
;   mov eax, val1
;   beginwhile:
;     cmp eax, val2
;     (6)______ endwhile  ; val1 >= val2 이면 종료 (부호 있는)
;     inc eax
;     jmp beginwhile
;   endwhile:
;
;   ※ 변수끼리는 직접 비교 불가 → 한쪽을 (7)______ 로 옮긴다

; ──────────────────────────────────────────────────────────
; [문제 4] 조건부 루프 명령어 — 빈칸을 채우세요.
;
;   LOOPE/LOOPZ  : ECX-- 후 (ECX!=0) 그리고 (ZF = (8)______ ) 이면 점프
;   LOOPNE/LOOPNZ: ECX-- 후 (ECX!=0) 그리고 (ZF = (9)______ ) 이면 점프
;
;   ★ LOOPxx 명령은 ZF를 (10)______ → 직전 명령의 ZF를 사용
;   ★ ADD 등이 ZF를 덮어쓰므로 (11)______ / (12)______ 로 플래그 보존

; ──────────────────────────────────────────────────────────
; [문제 5] 고수준 제어 흐름 디렉티브 — 빈칸을 채우세요.
;
;   IF 문   : .IF / .ELSEIF / .ELSE / (13)______
;   조건 먼저 검사하는 루프 : .WHILE / (14)______
;   몸체 먼저 실행 후 검사  : .REPEAT / (15)______
;
;   ★ 레지스터끼리 .IF 로 비교하면 MASM은 기본적으로
;     (16)______ 비교(JBE 등)를 생성한다

    ; (실행용 코드 - IF-ELSE)
    mov eax, op1
    cmp eax, op2
    jne L1
    mov X, 1
    jmp L2
L1: mov X, 2
L2:
    INVOKE ExitProcess, 0
main ENDP
END main
