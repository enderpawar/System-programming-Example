.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.DATA
    SetX  DWORD 80000007h
    SetY  DWORD 00000101h

.CODE
main PROC

; ──────────────────────────────────────────────────────────
; [문제 1] 명령어별 플래그 영향 — 빈칸을 채우세요.
;
;   AND  → OF = (1)______, CF = (2)______
;   OR   → OF = ______,    CF = ______        (AND와 동일)
;   XOR  → OF = ______,    CF = ______        (AND와 동일)
;   NOT  → 플래그 영향: (3)______
;   TEST → 동작은 (4)______ 와 같지만 (5)______ 는 변하지 않음
;   CMP  → 동작은 (6)______ 과 같지만 피연산자는 변하지 않음
; ──────────────────────────────────────────────────────────

; [문제 2] 비트 마스킹 — 알맞은 명령어를 채우세요.
;
;   · 특정 비트를 0으로 끄기(clear) → (7)______
;   · 특정 비트를 1로 켜기(set)     → (8)______
;   · 특정 비트를 토글(toggle)      → (9)______

; ──────────────────────────────────────────────────────────
; [문제 3] 대문자 변환 — 빈칸을 채우세요.
;
;   소문자 'a'(61h) → 대문자 'A'(41h) : 비트 (10)______ 만 다름
;   mov al, 'a'
;   and al, (11)______b      ; 비트5를 끄는 8비트 마스크
;   ; → AL = (12)______ ('A')

; ──────────────────────────────────────────────────────────
; [문제 4] 집합 연산 — 알맞은 명령어를 채우세요.
;
;   여집합(complement) → (13)______
;   교집합(intersection) → (14)______
;   합집합(union)        → (15)______
;
;   SetX=80000007h, SetY=00000101h 일 때
;   교집합 결과 EAX = (16)______
;   합집합 결과 EAX = (17)______

; ──────────────────────────────────────────────────────────
; [문제 5] XOR 가역성 — 빈칸을 채우세요.
;
;   (X XOR Y) XOR Y = (18)______
;   → 같은 키로 (19)______ 번 XOR 하면 원래 값 복원
;   → 이 성질을 이용한 암호화 방식: (20)______ 키 암호화

; ──────────────────────────────────────────────────────────
; [문제 6] CMP 결과 예측 — CF, ZF 값을 채우세요. (부호 없는)
;
;   mov ax, 5
;   cmp ax, 10     ; CF=(21)______  ZF=(22)______
;
;   mov ax, 1000
;   cmp ax, 1000   ; CF=(23)______  ZF=(24)______
;
;   mov ax, 105
;   cmp ax, 0      ; CF=(25)______  ZF=(26)______

    ; (실행용 코드 - 교집합/합집합 계산)
    mov eax, SetX
    and eax, SetY
    mov eax, SetX
    or  eax, SetY

    INVOKE ExitProcess, 0
main ENDP
END main
