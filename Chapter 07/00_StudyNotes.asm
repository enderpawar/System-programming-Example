; ╔══════════════════════════════════════════════════════════╗
; ║       SECTION 1: 시프트 & 로테이트                       ║
; ╚══════════════════════════════════════════════════════════╝
;
; ─────────────────────────────────────────────────────────
; 1-1. 명령어 한눈에 정리 (시험 단골!)
; ─────────────────────────────────────────────────────────
;   ┌──────┬────────────────────────────────────────────┐
;   │ 명령 │ 동작                                       │
;   ├──────┼────────────────────────────────────────────┤
;   │ SHL  │ 왼쪽 논리시프트, 최하위=0, 최상위→CF        │
;   │ SHR  │ 오른쪽 논리시프트, 최상위=0, 최하위→CF      │
;   │ SAL  │ SHL과 동일 (산술 왼쪽)                      │
;   │ SAR  │ 오른쪽 산술시프트, 부호비트 복제(부호 보존) │
;   │ ROL  │ 왼쪽 회전, 최상위→최하위 & CF               │
;   │ ROR  │ 오른쪽 회전, 최하위→최상위 & CF             │
;   │ RCL  │ CF 포함 왼쪽 회전 (CF를 9번째 비트처럼)     │
;   │ RCR  │ CF 포함 오른쪽 회전                         │
;   │ SHLD │ 더블 왼쪽시프트, 빈자리=소스의 상위비트     │
;   │ SHRD │ 더블 오른쪽시프트, 빈자리=소스의 하위비트   │
;   └──────┴────────────────────────────────────────────┘
;   ★ 모든 시프트/로테이트는 OF, CF에 영향
;
; ─────────────────────────────────────────────────────────
; 1-2. 시프트로 곱셈/나눗셈 (암기)
; ─────────────────────────────────────────────────────────
;   왼쪽 n비트 시프트 (SHL) = × 2^n
;   오른쪽 n비트 시프트(SHR)= ÷ 2^n  (부호 없는)
;   부호 있는 나눗셈        = SAR    (부호 비트 보존하므로)
;
;   ☑ 퀴즈 1: mov al,10 / shl al,2 후 AL=?  (답: 40 = 10×4)
;   ☑ 퀴즈 2: 부호 있는 -128 ÷ 8 을 하려면? (답: sar dl,3 → -16)
;
; ─────────────────────────────────────────────────────────
; 1-3. SAR로 부호 확장 / 부호 오버플로
; ─────────────────────────────────────────────────────────
;   AX→EAX 부호 확장: shl eax,16 / sar eax,16
;   1비트 시프트/회전으로 부호가 뒤집히면 OF=1
;   (카운트가 1보다 크면 OF는 정의되지 않음)

; ╔══════════════════════════════════════════════════════════╗
; ║       SECTION 2: 곱셈 & 나눗셈                           ║
; ╚══════════════════════════════════════════════════════════╝
;
; ─────────────────────────────────────────────────────────
; 2-1. MUL / IMUL 크기 규칙 (★★★ 최빈출 ★★★)
; ─────────────────────────────────────────────────────────
;   8비트  : AL  × op8  → AX
;   16비트 : AX  × op16 → DX:AX
;   32비트 : EAX × op32 → EDX:EAX
;   · 곱은 피연산자의 2배 크기 → 오버플로 불가
;   · 즉치 피연산자 사용 불가 (단, IMUL 2/3-피연산자 형식은 가능)
;
;   MUL  : 상위 절반 ≠ 0 이면 CF=1, OF=1
;   IMUL : 상위 절반이 하위의 부호확장이 아니면 CF=1, OF=1
;
;   ☑ 퀴즈 3: AX × BX 의 결과는 어느 레지스터에? (답: DX:AX)
;   ☑ 퀴즈 4: IMUL 48,4 → AX=192 인데 왜 OF=1?
;     (답: AH가 AL의 부호확장이 아님 → AL 최상위=1인데 AH=0)
;
; ─────────────────────────────────────────────────────────
; 2-2. DIV / IDIV 크기 규칙 (★★★ 최빈출 ★★★)
; ─────────────────────────────────────────────────────────
;   ┌────────┬──────────┬──────┬────────┐
;   │ 제수   │ 피제수   │ 몫   │ 나머지 │
;   ├────────┼──────────┼──────┼────────┤
;   │ 8비트  │ AX       │ AL   │ AH     │
;   │ 16비트 │ DX:AX    │ AX   │ DX     │
;   │ 32비트 │ EDX:EAX  │ EAX  │ EDX    │
;   └────────┴──────────┴──────┴────────┘
;
;   ★ DIV(부호 없는): 상위 절반(AH/DX/EDX)을 반드시 0으로 클리어
;   ★ IDIV(부호 있는): 나누기 전 반드시 부호 확장(CBW/CWD/CDQ)
;     CBW: AL→AX,  CWD: AX→DX,  CDQ: EAX→EDX
;   ★ IDIV 나머지의 부호 = 피제수의 부호
;
;   ☑ 퀴즈 5: 16비트 IDIV 전에 어떤 명령으로 부호 확장? (답: CWD)
;   ☑ 퀴즈 6: 8비트 -48/5 의 몫과 나머지는? (답: 몫 -9, 나머지 -3)
;
; ─────────────────────────────────────────────────────────
; 2-3. 나눗셈 오버플로
; ─────────────────────────────────────────────────────────
;   몫이 목적지에 안 들어가거나 0으로 나누면 → CPU 예외(프로그램 중단)
;   대책: 더 큰 피제수/제수 사용, 나누기 전 제수≠0 검사

; ╔══════════════════════════════════════════════════════════╗
; ║       SECTION 3: 확장 덧셈 & 뺄셈 (ADC / SBB)            ║
; ╚══════════════════════════════════════════════════════════╝
;
;   ADC 목적지, 소스 → 목적지 = 목적지 + 소스 + CF
;   SBB 목적지, 소스 → 목적지 = 목적지 - 소스 - CF
;   레지스터 크기를 넘는 큰 수를 조각내어 Carry를 전달하며 계산
;
;   FFh + FFh:
;     add al,0FFh (CF=1) → adc dl,0 (DL=1) → DL:AL = 01FEh
;
;   ☑ 퀴즈 7: 0FFFFFFFFh + 0FFFFFFFFh 의 EDX:EAX 결과?
;     (답: 00000001FFFFFFFEh)

; ╔══════════════════════════════════════════════════════════╗
; ║       SECTION 4: 흔한 실수 모음                          ║
; ╚══════════════════════════════════════════════════════════╝
;
; ✗ 실수 1: DIV 전에 AH/DX/EDX 클리어 안 함 → 엉뚱한 몫/예외
; ✗ 실수 2: IDIV 전에 부호 확장(CBW/CWD/CDQ) 안 함 → 오답
; ✗ 실수 3: 부호 있는 나눗셈에 SHR 사용 (SAR를 써야 부호 보존)
; ✗ 실수 4: MUL에 즉치 피연산자 사용 (mul 5 ← 불가)
; ✗ 실수 5: 곱셈 결과를 AX 한 곳에만 있다고 가정
;           (16비트는 DX:AX, 32비트는 EDX:EAX)
; ✗ 실수 6: ADC/SBB로 큰 수 계산 시 Carry 전달 순서 착각
;           (덧셈/뺄셈은 하위 조각부터 처리해야 CF가 맞음)

