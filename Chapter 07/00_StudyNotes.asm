; ║       SECTION 5: 퀴즈 정답 모음                          ║
; ╚══════════════════════════════════════════════════════════╝
;
; Q1: shl al,2 → AL = 40 (10 × 4)
; Q2: sar dl,3 → -128 ÷ 8 = -16 (SAR로 부호 보존)
; Q3: AX × BX → DX:AX
; Q4: AH가 AL의 부호확장이 아니므로 OF=1 (192=00C0h, AL=C0h,AH=00h)
; Q5: CWD (AX → DX 부호 확장)
; Q6: -48/5 → 몫 -9, 나머지 -3
; Q7: 00000001FFFFFFFEh
