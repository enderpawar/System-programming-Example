; ============================================================
; 파일명  : 20_MulDiv.asm
; 설  명  : 7장 정수 산술 (3) - 곱셈 & 나눗셈 명령어
;           MUL / IMUL / DIV / IDIV / CBW / CWD / CDQ
;           (PDF 07_Integer Arithmetic - Multiplication and Division)
; ============================================================
;
; [MUL/IMUL 피연산자-결과 크기 규칙 (암기!)]
;   ┌────────┬──────────┬──────────────┐
;   │ 피연산자│ 곱해지는 │ 결과 위치     │
;   ├────────┼──────────┼──────────────┤
;   │ 8비트  │ AL       │ AX           │
;   │ 16비트 │ AX       │ DX:AX        │
;   │ 32비트 │ EAX      │ EDX:EAX      │
;   └────────┴──────────┴──────────────┘
;   ※ 곱은 항상 피연산자의 2배 크기 → 오버플로 불가
;   ※ 즉치 피연산자 불가 (레지스터/메모리만)
;
; [DIV/IDIV 피연산자-결과 규칙 (암기!)]
;   ┌────────┬──────────┬────────┬────────┐
;   │ 제수   │ 피제수   │ 몫     │ 나머지 │
;   ├────────┼──────────┼────────┼────────┤
;   │ 8비트  │ AX       │ AL     │ AH     │
;   │ 16비트 │ DX:AX    │ AX     │ DX     │
;   │ 32비트 │ EDX:EAX  │ EAX    │ EDX    │
;   └────────┴──────────┴────────┴────────┘
; ============================================================

.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.DATA
    val32 DWORD 7FFFh

.CODE
main PROC

    ; ==========================================================
    ; 1. MUL (Unsigned Multiply) - 부호 없는 곱셈
    ;    상위 절반이 0이 아니면 CF=1, OF=1 (결과가 하위에 안 들어감)
    ; ==========================================================

    ; 8비트: AL × BL → AX
    mov al, 5h
    mov bl, 10h
    mul bl                 ; AX = 0050h, CF=0 (AH=0이므로)

    ; 16비트: AX × BX → DX:AX
    mov ax, 2000h
    mov bx, 0100h
    mul bx                 ; DX:AX = 00200000h, CF=1 (DX!=0)

    ; 32비트: EAX × EBX → EDX:EAX
    mov eax, 12345h
    mov ebx, 1000h
    mul ebx                ; EDX:EAX = 0000000012345000h, CF=0

    ; ==========================================================
    ; 2. IMUL (Signed Multiply) - 부호 있는 곱셈
    ;    부호를 보존(상위로 부호 확장)
    ;    상위 절반이 하위의 부호 확장이 '아니면' CF=1, OF=1
    ; ==========================================================

    ; 1-피연산자 형식: 48 × 4 = +192
    mov al, 48
    mov bl, 4
    imul bl                ; AX = 192. 단, AH가 AL의 부호확장이
                           ; 아니므로(AL 최상위=1) OF=1

    ; 1-피연산자 형식: -4 × 4 = -16
    mov al, -4
    mov bl, 4
    imul bl                ; AX = -16 (FFF0h), AH가 부호확장 → OF=0

    ; 2-피연산자 형식: 목적지(레지스터) = 목적지 × 소스
    ;   결과를 목적지 크기로 자름 → 유효 자리 손실 시 OF=1,CF=1
    mov eax, 4823424
    mov ebx, -423
    imul ebx, eax          ; EBX = EBX × EAX (32비트로 잘림)

    ; 3-피연산자 형식: 목적지 = 소스 × 즉치
    imul ebx, eax, 10      ; EBX = EAX × 10

    ; ==========================================================
    ; 3. DIV (Unsigned Divide) - 부호 없는 나눗셈
    ;    피제수의 상위 절반(AH/DX/EDX)을 반드시 0으로 클리어!
    ; ==========================================================

    ; 8비트: 83h / 2 → 몫 41h, 나머지 1
    mov ax, 0083h          ; 피제수 = AX (AH=0)
    mov bl, 2
    div bl                 ; AL = 41h (몫), AH = 1 (나머지)

    ; 16비트: 8003h / 100h → 몫 80h, 나머지 3
    mov dx, 0              ; ★ 상위 절반 DX를 반드시 클리어
    mov ax, 8003h
    mov cx, 100h
    div cx                 ; AX = 0080h (몫), DX = 0003h (나머지)

    ; 32비트: 메모리 제수 사용
    mov edx, 0             ; ★ EDX 클리어
    mov eax, 10000h
    div val32              ; EAX = 몫, EDX = 나머지

    ; ==========================================================
    ; 4. 부호 확장 명령어 (CBW / CWD / CDQ)
    ;    부호 있는 나눗셈 전에 피제수를 반드시 부호 확장!
    ;    CBW : AL → AX  (Byte → Word)
    ;    CWD : AX → DX  (Word → Doubleword, DX:AX)
    ;    CDQ : EAX → EDX (Doubleword → Quadword, EDX:EAX)
    ; ==========================================================

    ; ==========================================================
    ; 5. IDIV (Signed Divide) - 부호 있는 나눗셈
    ;    나머지의 부호는 항상 피제수와 같음
    ; ==========================================================

    ; 8비트: -48 / 5 → 몫 -9, 나머지 -3
    mov al, -48
    cbw                    ; AL을 AX로 부호 확장 (AX = FFD0h)
    mov bl, 5
    idiv bl                ; AL = -9 (몫), AH = -3 (나머지)

    ; 16비트: -5000 / 256 → 몫 -19, 나머지 -136
    mov ax, -5000
    cwd                    ; AX를 DX로 부호 확장
    mov bx, 256
    idiv bx                ; AX = -19 (몫), DX = -136 (나머지)

    ; 32비트: 50000 / -256 → 몫 -195, 나머지 80
    mov eax, 50000
    cdq                    ; EAX를 EDX로 부호 확장
    mov ebx, -256
    idiv ebx               ; EAX = -195 (몫), EDX = 80 (나머지)

    ; ==========================================================
    ; 6. 나눗셈 오버플로 (Divide Overflow) - 주의!
    ;    몫이 목적지에 안 들어가거나 0으로 나누면
    ;    CPU 예외 발생 → 프로그램 중단
    ;    예) AX=100h 를 8비트로 나누면 몫이 AL을 초과 → 예외
    ;    대책: 더 큰 피제수/제수 사용, 나누기 전 제수≠0 검사
    ; ==========================================================

    INVOKE ExitProcess, 0
main ENDP

END main
