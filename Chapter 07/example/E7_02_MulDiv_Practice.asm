; 빈칸( ______ )을 채우세요. 정답은 E7_02_MulDiv_Answer.asm 참고.
; ============================================================

.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.CODE
main PROC

; ──────────────────────────────────────────────────────────
; [문제 1] MUL / IMUL 크기 규칙 — 빈칸을 채우세요.
;
;   8비트  : AL  × op → 결과는 (1)______
;   16비트 : AX  × op → 결과는 (2)______
;   32비트 : EAX × op → 결과는 (3)______
;
;   · 곱은 피연산자의 (4)______ 배 크기 → 오버플로 불가
;   · MUL은 상위 절반이 0이 아니면 CF=(5)______, OF=(5)______
; ──────────────────────────────────────────────────────────

; [문제 2] DIV / IDIV 크기 규칙 — 빈칸을 채우세요.
;
;   ┌────────┬──────────┬──────┬────────┐
;   │ 제수   │ 피제수   │ 몫   │ 나머지 │
;   ├────────┼──────────┼──────┼────────┤
;   │ 8비트  │ (6)____  │ AL   │ (7)____│
;   │ 16비트 │ (8)____  │ AX   │ DX     │
;   │ 32비트 │EDX:EAX   │(9)___│ EDX    │
;   └────────┴──────────┴──────┴────────┘

; ──────────────────────────────────────────────────────────
; [문제 3] 부호 없는 나눗셈 — 빈칸을 채우세요.
;   83h / 2
;
;   mov ax, 0083h        ; 피제수 (AH=(10)______ 로 클리어 필수)
;   mov bl, 2
;   div bl               ; AL = (11)______ (몫), AH = (12)______ (나머지)
;
;   ★ DIV 전에 반드시 상위 절반(AH/DX/EDX)을 (13)______ 로 만든다

; ──────────────────────────────────────────────────────────
; [문제 4] 부호 확장 명령어 — 빈칸을 채우세요.
;
;   CBW : AL → (14)______
;   CWD : AX → (15)______
;   CDQ : EAX → (16)______

; ──────────────────────────────────────────────────────────
; [문제 5] 부호 있는 나눗셈 — 빈칸을 채우세요.
;   -48 / 5
;
;   mov al, -48
;   (17)______           ; AL을 AX로 부호 확장
;   mov bl, 5
;   idiv bl              ; AL = (18)______ (몫), AH = (19)______ (나머지)
;
;   ★ IDIV 나머지의 부호는 (20)______ 의 부호와 같다

    ; (실행용 코드 - 부호 있는 나눗셈)
    mov al, -48
    cbw
    mov bl, 5
    idiv bl

    INVOKE ExitProcess, 0
main ENDP
END main
