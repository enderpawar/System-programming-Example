; ★★★ 최우선 암기 항목 ★★★
;
; 1. 시프트/로테이트 명령어
;    SHL/SAL → 왼쪽, 최하위=0, 최상위→CF
;    SHR     → 오른쪽(논리), 최상위=0
;    SAR     → 오른쪽(산술), 부호 비트 복제 (부호 보존)
;    ROL/ROR → 회전, RCL/RCR → CF 포함 회전
;    ★ 모두 OF, CF 에 영향
;
; 2. 시프트로 곱셈/나눗셈
;    SHL n = ×2^n,  SHR n = ÷2^n (부호 없는)
;    부호 있는 나눗셈 → SAR (부호 보존!)
;    AX→EAX 부호확장: shl eax,16 / sar eax,16
;
; 3. MUL / IMUL 크기 규칙 (★★★ 최빈출 ★★★)
;    8비트  AL ×op → AX
;    16비트 AX ×op → DX:AX
;    32비트 EAX×op → EDX:EAX
;    MUL : 상위절반≠0 → CF=1,OF=1
;    IMUL: 상위절반이 부호확장 아니면 → CF=1,OF=1
;    ※ MUL은 즉치 불가 (IMUL 2/3-피연산자만 즉치 가능)
;
; 4. DIV / IDIV 크기 규칙 (★★★ 최빈출 ★★★)
;    8비트  AX     ÷op → 몫 AL,  나머지 AH
;    16비트 DX:AX  ÷op → 몫 AX,  나머지 DX
;    32비트 EDX:EAX÷op → 몫 EAX, 나머지 EDX
;    ★ DIV  : 상위절반(AH/DX/EDX) 반드시 0으로 클리어
;    ★ IDIV : 나누기 전 반드시 부호확장 (CBW/CWD/CDQ)
;       CBW: AL→AX,  CWD: AX→DX,  CDQ: EAX→EDX
;    ★ IDIV 나머지 부호 = 피제수 부호
;    ★ 나눗셈 오버플로/0 나눗셈 → CPU 예외(프로그램 중단)
;
; 5. 예제 값 (외워두면 유리)
;    -48 / 5  → 몫 -9, 나머지 -3
;    83h / 2  → 몫 41h, 나머지 1
;    48 × 4 (IMUL) → AX=192, OF=1 (AH가 부호확장 아님)
;
; 6. 이진 곱셈 (SHL+ADD)
;    123 × 36, 36 = 2^5 + 2^2
;    shl eax,5 / shl ebx,2 / add → 4428
;
; 7. 비트 필드 추출 (시프트+마스크)
;    오른쪽 시프트로 필드를 하위로 옮긴 뒤 AND 마스크
;
; 8. 확장 덧셈/뺄셈 (ADC / SBB)
;    ADC: 목적지 = 목적지 + 소스 + CF
;    SBB: 목적지 = 목적지 - 소스 - CF
;    하위 조각부터 처리 → Carry를 상위로 전달
;    0FFFFFFFFh + 0FFFFFFFFh → EDX:EAX = 00000001FFFFFFFEh
