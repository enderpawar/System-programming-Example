; ============================================================
; [시험 대비 빈칸 채우기] 7장 - 확장 덧셈 & 뺄셈 (ADC / SBB)
; 빈칸( ______ )을 채우세요. 정답은 E7_03_Extended_Answer.asm 참고.
; ============================================================

.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.CODE
main PROC

; ──────────────────────────────────────────────────────────
; [문제 1] ADC / SBB 의미 — 빈칸을 채우세요.
;
;   ADC 목적지, 소스 → 목적지 = 목적지 + 소스 + (1)______
;   SBB 목적지, 소스 → 목적지 = 목적지 - 소스 - (2)______
;
;   용도: 레지스터 크기를 넘는 (3)______ 정수를 조각내어
;         (4)______ 를 다음 조각으로 전달하며 계산
; ──────────────────────────────────────────────────────────

; [문제 2] 8비트 합을 16비트로 (FFh + FFh) — 빈칸을 채우세요.
;
;   mov dl, 0
;   mov al, 0FFh
;   add al, 0FFh      ; AL = (5)______, CF = (6)______
;   (7)______ dl, 0   ; DL = 0 + 0 + CF = (8)______
;   ; → DL:AL = (9)______   (255 + 255 = 510)

; ──────────────────────────────────────────────────────────
; [문제 3] 32비트 합을 64비트로 — 빈칸을 채우세요.
;   0FFFFFFFFh + 0FFFFFFFFh
;
;   mov edx, 0
;   mov eax, 0FFFFFFFFh
;   add eax, 0FFFFFFFFh   ; EAX = FFFFFFFEh, CF = (10)______
;   adc edx, 0            ; EDX = (11)______
;   ; → EDX:EAX = (12)______

; ──────────────────────────────────────────────────────────
; [문제 4] 64비트 뺄셈 (SBB) — 빈칸을 채우세요.
;   EDX:EAX(=0000000100000000h) 에서 1 빼기
;
;   mov edx, 1
;   mov eax, 0
;   sub eax, 1            ; EAX = (13)______, CF = (14)______ (빌림)
;   (15)______ edx, 0    ; EDX = 1 - 0 - CF = (16)______
;   ; → EDX:EAX = 00000000FFFFFFFFh

    ; (실행용 코드 - 8비트 → 16비트 덧셈)
    mov dl, 0
    mov al, 0FFh
    add al, 0FFh
    adc dl, 0

    INVOKE ExitProcess, 0
main ENDP
END main
