; ============================================================
; [시험 대비 빈칸 채우기] 7장 - 시프트 & 로테이트
; 빈칸( ______ )을 채우세요. 정답은 E7_01_ShiftRotate_Answer.asm 참고.
; ============================================================

.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.DATA
    datestamp WORD 266Ah     ; 1999-03-10

.CODE
main PROC

; ──────────────────────────────────────────────────────────
; [문제 1] 명령어 동작 — 빈칸을 채우세요.
;
;   SHL : 왼쪽 논리시프트, 최하위에 (1)______ 채움, 최상위→(2)______
;   SHR : 오른쪽 논리시프트, 최상위에 (3)______ 채움
;   SAR : 오른쪽 산술시프트, 빈자리를 (4)______ 비트로 채움(부호 보존)
;   ROL : 왼쪽 회전, 최상위 비트가 (5)______ 자리와 CF로 복사
;   RCL : (6)______ 를 포함한 왼쪽 회전
;
;   ★ 모든 시프트/로테이트가 영향을 주는 두 플래그: (7)______, (8)______
; ──────────────────────────────────────────────────────────

; [문제 2] 시프트로 곱셈/나눗셈 — 빈칸을 채우세요.
;
;   왼쪽 n비트 시프트 = × (9)______
;   오른쪽 n비트 시프트(부호 없는) = ÷ (10)______
;   부호 있는 나눗셈에는 (11)______ 명령을 써야 부호가 보존됨
;
;   mov al, 10
;   shl al, 2      ; AL = (12)______   (10 × 4)
;
;   mov dl, -128
;   sar dl, 3      ; DL = (13)______   (-128 ÷ 8)

; ──────────────────────────────────────────────────────────
; [문제 3] 이진 곱셈 (SHL+ADD) — 빈칸을 채우세요.
;   123 × 36 을 구한다.  36 = 2^5 + 2^(14)______
;
;   mov eax, 123
;   mov ebx, eax
;   shl eax, (15)______    ; 123 × 32
;   shl ebx, (16)______    ; 123 × 4
;   add eax, ebx           ; = (17)______  (123 × 36)

; ──────────────────────────────────────────────────────────
; [문제 4] 파일 날짜 필드 추출 — 빈칸을 채우세요.
;   datestamp(266Ah): 비트0~4=일, 비트5~8=월, 비트9~15=연도(1980기준)
;
;   ; 일 추출
;   mov ax, datestamp
;   and ax, (18)______b           ; 하위 5비트 마스크 → AX = 10
;
;   ; 월 추출
;   mov ax, datestamp
;   shr ax, (19)______
;   and ax, 0000000000001111b     ; AX = 3
;
;   ; 연도 추출
;   mov ax, datestamp
;   shr ax, (20)______
;   add ax, (21)______            ; AX = 1999

    ; (실행용 코드 - 연도 추출)
    mov ax, datestamp
    shr ax, 9
    add ax, 1980

    INVOKE ExitProcess, 0
main ENDP
END main
