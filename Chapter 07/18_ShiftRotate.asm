; ============================================================
; 파일명  : 18_ShiftRotate.asm
; 설  명  : 7장 정수 산술 (1) - 시프트 & 로테이트 명령어
;           SHL / SHR / SAL / SAR / ROL / ROR / RCL / RCR /
;           SHLD / SHRD
;           (PDF 07_Integer Arithmetic - Shift and Rotate Instructions)
; ============================================================
;
; [논리 시프트 vs 산술 시프트]
;   논리(Logical)   : 새로 생기는 비트 자리를 0으로 채움
;   산술(Arithmetic): 새 비트 자리를 원래 부호 비트로 채움(부호 보존)
;
; [공통] 모든 시프트/로테이트는 OF, CF에 영향을 준다.
;        카운트는 즉치(0~255) 또는 CL 레지스터 사용.
; ============================================================

.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.DATA
    testval BYTE 11001111b

.CODE
main PROC

    ; ==========================================================
    ; 1. SHL (Shift Left) - 논리 왼쪽 시프트
    ;    최하위 비트에 0을 채우고, 최상위 비트는 CF로 나감
    ; ==========================================================
    mov bl, 8Fh            ; BL = 10001111b
    shl bl, 1              ; BL = 00011110b, CF=1 (밀려난 최상위 비트)

    ; [비트 곱셈] 왼쪽 n비트 시프트 = ×2^n
    mov dl, 5
    shl dl, 1              ; DL = 10  (5 × 2^1)
    mov dl, 10            ; 00001010b
    shl dl, 2             ; DL = 40  (10 × 2^2)

    ; ==========================================================
    ; 2. SHR (Shift Right) - 논리 오른쪽 시프트
    ;    최상위 비트에 0을 채우고, 최하위 비트는 CF로 나감
    ; ==========================================================
    mov al, 0D0h           ; AL = 11010000b
    shr al, 1              ; AL = 01101000b, CF=0

    ; [비트 나눗셈] 오른쪽 n비트 시프트 = ÷2^n (부호 없는)
    mov al, 32
    shr al, 3             ; AL = 4  (32 ÷ 2^3)

    ; ==========================================================
    ; 3. SAL / SAR - 산술 시프트
    ;    SAL : SHL과 완전히 동일 (왼쪽)
    ;    SAR : 오른쪽 시프트하되 부호 비트를 복제(부호 보존)
    ; ==========================================================

    ; SAR로 부호 보존 확인 (음수는 음수로 유지)
    mov al, 0F0h           ; AL = -16 (11110000b)
    sar al, 1             ; AL = 11111000b = -8 (부호 비트 복제)

    ; [부호 있는 나눗셈] SAR 사용: -128 ÷ 2^3 = -16
    mov dl, -128           ; DL = 10000000b
    sar dl, 3             ; DL = 11110000b = -16

    ; [AX의 부호를 EAX로 확장하는 기법]
    ;   왼쪽 16비트 시프트 후 산술 오른쪽 16비트 시프트
    mov eax, 0FFFFh        ; 하위 워드만 채워진 상태 가정
    shl eax, 16
    sar eax, 16           ; 부호 확장 완료

    ; ==========================================================
    ; 4. ROL (Rotate Left) - 왼쪽 회전
    ;    최상위 비트가 최하위 비트 자리 + CF 로 동시에 복사됨
    ;    회전은 비트를 잃지 않음(한 끝에서 나간 비트가 반대편으로)
    ; ==========================================================
    mov al, 11110000b
    rol al, 1             ; AL = 11100001b (최상위 1 → 최하위)

    ; [니블 교환] 바이트의 상위4/하위4 비트 교환 → 4비트 회전
    mov al, 26h
    rol al, 4            ; AL = 62h (16진수 자리 교환)

    ; ==========================================================
    ; 5. ROR (Rotate Right) - 오른쪽 회전
    ;    최하위 비트가 최상위 비트 자리 + CF 로 복사됨
    ; ==========================================================
    mov al, 11110000b
    ror al, 1            ; AL = 01111000b (최하위 0 → 최상위)

    ; ==========================================================
    ; 6. RCL (Rotate Carry Left) - CF를 포함한 왼쪽 회전
    ;    CF를 최하위 비트로, 최상위 비트를 CF로 (CF가 9번째 비트)
    ; ==========================================================
    clc                   ; CF = 0
    mov bl, 88h            ; BL = 10001000b, CF=0
    rcl bl, 1            ; CF=1, BL=00010000b (최상위→CF, CF→최하위)
    rcl bl, 1            ; CF=0, BL=00100001b

    ; ==========================================================
    ; 7. RCR (Rotate Carry Right) - CF를 포함한 오른쪽 회전
    ;    CF를 최상위 비트로, 최하위 비트를 CF로
    ; ==========================================================
    stc                   ; CF = 1
    mov ah, 10h           ; AH = 00010000b, CF=1
    rcr ah, 1            ; AH = 10001000b, CF=0 (CF→최상위)

    ; ==========================================================
    ; 8. 부호 오버플로 (시프트/로테이트의 OF)
    ;    1비트 시프트/회전으로 부호가 뒤집히면 OF=1
    ;    예) +127 을 왼쪽 회전 → 음수가 되면 OF=1
    ;    (카운트가 1보다 크면 OF는 정의되지 않음)
    ; ==========================================================
    mov al, +127           ; 01111111b
    rol al, 1            ; 11111110b = -2 → 부호 반전 → OF=1

    ; ==========================================================
    ; 9. SHLD / SHRD (Double Precision Shift)
    ;    SHLD 목적지, 소스, 카운트
    ;      목적지를 왼쪽으로 시프트, 빈 자리를 '소스의 상위비트'로 채움
    ;    SHRD 목적지, 소스, 카운트
    ;      목적지를 오른쪽으로 시프트, 빈 자리를 '소스의 하위비트'로 채움
    ;    ※ 소스는 변하지 않으며 반드시 레지스터여야 함
    ; ==========================================================
    mov ax, 234Bh
    mov dx, 7654h
    shrd ax, dx, 4       ; AX를 오른쪽 4비트, DX 하위4비트가 AX 상위로

    INVOKE ExitProcess, 0
main ENDP

END main
