; ============================================================
; 파일명  : 19_ShiftRotateApplications.asm
; 설  명  : 7장 정수 산술 (2) - 시프트 & 로테이트 응용
;           다중 더블워드 시프트 / 이진 곱셈 / 비트 필드 추출
;           (PDF 07_Integer Arithmetic - Shift and Rotate Applications)
; ============================================================

.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.DATA
    ; 확장 정수: 리틀 엔디안으로 저장된 바이트 배열
    ArrayVal BYTE 81h, 20h, 33h        ; 최하위 바이트가 가장 앞

    ; 파일 날짜 스탬프 예제: 1999년 3월 10일
    ;   비트 0~4 = 일(10), 비트 5~8 = 월(3), 비트 9~15 = 연도(19, 1980기준)
    datestamp WORD 266Ah

.CODE
main PROC

    ; ==========================================================
    ; 1. 다중 바이트(확장 정수) 1비트 오른쪽 시프트
    ;    리틀 엔디안 배열을 '높은 바이트부터' 처리해야
    ;    밀려난 비트를 CF로 이어받아 다음 바이트로 전달 가능
    ;
    ;    Step1: 최상위 바이트 [esi+2] SHR → 최하위 비트가 CF로
    ;    Step2: [esi+1] RCR → CF를 최상위로 받고 최하위를 CF로
    ;    Step3: [esi]   RCR → 동일하게 처리
    ; ==========================================================
    mov esi, OFFSET ArrayVal
    shr BYTE PTR [esi+2], 1   ; 최상위 바이트, 최하위 비트 → CF
    rcr BYTE PTR [esi+1], 1   ; CF를 최상위로 채우고, 최하위 → CF
    rcr BYTE PTR [esi], 1     ; 마지막 바이트도 동일 처리
    ; → 전체 24비트가 1비트 오른쪽으로 이동 완료

    ; ==========================================================
    ; 2. 이진 곱셈 (SHL + ADD 로 MUL 대체)
    ;    승수가 2의 거듭제곱들의 합이면 SHL로 분해 가능
    ;    예) 123 × 36,  36 = 2^5 + 2^2 (비트 5,2 가 set)
    ; ==========================================================
    mov eax, 123
    mov ebx, eax
    shl eax, 5             ; 123 × 2^5 = 123 × 32
    shl ebx, 2             ; 123 × 2^2 = 123 × 4
    add eax, ebx           ; = 123 × 36 = 4428

    ; ==========================================================
    ; 3. 파일 날짜 필드 추출 (비트 문자열 분리)
    ;    하나의 정수에 여러 필드가 패킹됨 → 시프트+마스크로 추출
    ;    datestamp = 266Ah  (1999-03-10)
    ; ==========================================================

    ; (1) 일(day) 추출: 비트 0~4 → 하위 5비트 마스크
    mov ax, datestamp
    and ax, 0000000000011111b   ; AX = 10 (일)

    ; (2) 월(month) 추출: 비트 5~8 → 오른쪽 5시프트 후 4비트 마스크
    mov ax, datestamp
    shr ax, 5
    and ax, 0000000000001111b   ; AX = 3 (월)

    ; (3) 연도(year) 추출: 비트 9~15 → 오른쪽 9시프트, 1980 더하기
    mov ax, datestamp
    shr ax, 9
    add ax, 1980                ; AX = 1999 (연도)

    INVOKE ExitProcess, 0
main ENDP

END main
