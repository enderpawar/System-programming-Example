.386
.MODEL flat, stdcall
.STACK 4096

ExitProcess PROTO, dwExitCode:DWORD

.DATA
    var1  BYTE  10h
    var2  BYTE  20h
    xval  WORD  100
    yval  WORD  200

.CODE
main PROC

; ──────────────────────────────────────────────────────────
; [문제 1] MOV 규칙 — 다음 조합이 가능(O) 또는 불가(X) 인지 표시하세요.
;
;   a) MOV reg, imm    (즉치 → 레지스터)      : (1)______ 
;   b) MOV reg, reg    (레지스터 → 레지스터)  : (2)______ 
;   c) MOV mem, mem    (메모리 → 메모리)      : (3)______ 
;   d) MOV mem, reg    (레지스터 → 메모리)    : (4)______
;   e) MOV mem, imm    (즉치 → 메모리)        : (5)______
;   f) MOV eax, bl     (크기 불일치 이동)     : (6)______
; ──────────────────────────────────────────────────────────

; [문제 2] 다음 코드 중 오류인 줄을 모두 찾고 수정하세요.
;
;   (줄A)  mov var2, var1      ; (7) 올바름 / 오류 — 이유: ______
;   (줄B)  mov eax, bl        ; (8) 올바름 / 오류 — 이유: ______
;   (줄C)  mov al, 0FFh       ; (9) 올바름 / 오류
;   (줄D)  mov eax, 0         ; (10) 올바름 / 오류
;
;   (줄A) 의 올바른 수정:
;       mov (11)______, var1
;       mov var2, (12)______
;
;   (줄B) 의 올바른 수정:
;       (13)______ eax, bl    ; 부호 없는 경우 movzx 
;       (14)______ eax, bl    ; 부호 있는 경우 movsx 

; ──────────────────────────────────────────────────────────
; [문제 3] 겹치는 레지스터 (Overlapping Registers)
;
;   EAX = 12345678h 상태에서:
;
;   mov AL, 0AAh 실행 후 EAX = (15)______ ;123456AAh 
;   (상위 3바이트는 (16) 변함 / 그대로 유지)
;
;   EAX의 구조:
;     EAX  = 32비트 전체
;     AX   = EAX의 (17)______ 16비트 
;     AH   = AX의  (18)______ 8비트
;     AL   = AX의  (19)______ 8비트
; ──────────────────────────────────────────────────────────

; [문제 4] MOVZX vs MOVSX — 실행 결과를 채우세요.
;
;   BL = 0A0h (= 1010_0000b)
;
;   movzx eax, bl  →  EAX = (20)______   ; (21)______ 확장 (부호 없는 값에 사용) ;부호없는 
;   movsx eax, bl  →  EAX = (22)______   ; (23)______ 확장 (부호 있는 값에 사용) ; 부호있는 
;ㅌ
;   [추가 문제] BL = 0F0h 일 때:
;   movzx eax, bl  →  EAX = (24)______   ; 0F0h = 10진수 (25)______  ; 0000 00F0h 
;   movsx eax, bl  →  EAX = (26)______   ; 0F0h 부호 있는 해석 = (27)______ FFFF FFF0h 

; ──────────────────────────────────────────────────────────
; [문제 5] XCHG — 두 메모리 변수를 교환하는 코드를 완성하세요.
;          (XCHG는 메모리-메모리 직접 교환 불가)
;
;   xval = 100, yval = 200 교환 목표:
;
;   mov  ax, xval           ; AX = 100
;   (28)______ ax, yval     ; AX ↔ yval → AX = 200, yval = 100 
;   mov  xval, (29)______   ; xval = 200
;
;   교환 후: xval = (30)______, yval = (31)______

; ──────────────────────────────────────────────────────────
; [문제 6] 직접 오프셋 피연산자 (Direct-Offset Operands)
;
;   arrayB  BYTE  10h, 20h, 30h, 40h, 50h
;
;   mov al, arrayB          ; AL = (32)______  (인덱스 0)  ; ArrayB는 배열이 시작되는 시작 주소를 의미하므로, 이렇게 됨
;   mov al, [arrayB + 1]    ; AL = (33)______  (인덱스 1)  ;  
;   mov al, [arrayB + 4]    ; AL = (34)______  (인덱스 4)
;
;   WORD 배열에서 두 번째 원소 접근 (arrayW WORD 100h, 200h, 300h):
;   mov ax, [arrayW + (35)______]    ; AX = 200h  (WORD는 2바이트 간격) ; TYPE WORD 

    INVOKE ExitProcess, 0
main ENDP
END main

